				PackageId = rule.wszPackageId?.value,
				LocalUserOwner = rule.wszLocalUserOwner?.value,
				TrustTupleKeywords = rule.dwTrustTupleKeywords,
				OnNetworkNames = rule.OnNetworkNames.wszNames?.value.UnwrapArray(),
				SecurityRealmId = rule.wszSecurityRealmId?.value,
				RemoteOutServerNames = rule.RemoteOutServerNames.wszNames?.value.UnwrapArray(),
				FullyQualifiedBinaryName = rule.wszFqbn?.value,
				CompartmentId = rule.compartmentId,
				ProviderContextKey = rule.providerContextKey,
				RemoteDynamicKeywordAddresses = rule.RemoteDynamicKeywordAddresses.ids?.value
			};
			ruleInfo.SetPortList(
				rule.wIpProtocol,
				rule.unnamed_1.__unnamed_0.LocalPorts,
				rule.unnamed_1.__unnamed_0.RemotePorts,
				rule.unnamed_1.V4TypeCodeList,
				rule.unnamed_1.V6TypeCodeList
				);
			return ruleInfo;
		}

		private static FirewallObjectMetadata[] CreateNewOnMetadata(RpcPointer<FW_OBJECT_METADATA[]> pMetaData)
		{
			if (pMetaData is null)
				return null;

			return Array.ConvertAll(pMetaData.value, r =>
			{
				FW_ENFORCEMENT_STATE[]? enfStates = r.pEnforcementStates.value;
				return new FirewallObjectMetadata
				{
					FilterContextId = r.qwFilterContextID,
					EnforcementStateValues = (enfStates == null) ? null : Array.ConvertAll(enfStates, r => (EnforcementState)r)
				};
			});
		}

