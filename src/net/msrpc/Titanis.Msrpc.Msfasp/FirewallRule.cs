			(list is null) ? null
			: new IcmpTypeCodeList(list.value.Select(r => new IcmpTypeCode(r.bType, r.wCode)).ToArray());

		public static implicit operator FirewallRule(in FW_RULE2_0 rule)
		{
			FirewallRule ruleInfo = new()
			{
				RuleId = rule.wszRuleId.value,
				SchemaVersion = rule.wSchemaVersion,
				Name = rule.wszName.value,
				Description = rule.wszDescription?.value,
				Action = (FirewallRuleAction)rule.Action,
				Profiles = (FirewallProfiles)rule.dwProfiles,
				Direction = (FirewallRuleDirection)rule.Direction,
				IpProtocol = (IpProtocolNumber)rule.wIpProtocol,
				LocalApplication = rule.wszLocalApplication?.value,
				LocalService = rule.wszLocalService?.value,
				Interfaces = rule.LocalInterfaceIds.pLUIDs?.value?.ToArray(),
				InterfaceTypes = (InterfaceTypes)rule.dwLocalInterfaceTypes,
				Status = (FirewallRuleStatus)rule.Status,
				RemoteMachines = rule.wszRemoteMachineAuthorizationList?.value,
				RemoteUsers = rule.wszRemoteUserAuthorizationList?.value,
				EmbeddedContext = rule.wszEmbeddedContext?.value,
				Origin = (FirewallRuleOrigin)rule.Origin,
				GpoName = rule.wszGPOName?.value,
				Flags = (FirewallRuleFlags)rule.wFlags,
			};
			ruleInfo.SetPortList(
				rule.wIpProtocol,
				rule.unnamed_1.__unnamed_0.LocalPorts,
				rule.unnamed_1.__unnamed_0.RemotePorts,
				rule.unnamed_1.V4TypeCodeList,
				rule.unnamed_1.V6TypeCodeList
				);
			return ruleInfo;
		}

		private void SetPortList(
			ushort protocol,
			in FW_PORTS localPorts,
			in FW_PORTS remotePorts,
			in FW_ICMP_TYPE_CODE_LIST icmp4,
			in FW_ICMP_TYPE_CODE_LIST icmp6
			)
		{
			switch ((IpProtocolNumber)protocol)
			{
				case IpProtocolNumber.Tcp or IpProtocolNumber.Udp:
					this.LocalPortList = new PortList(localPorts);
					this.RemotePortList = new PortList(remotePorts);
					break;
				case IpProtocolNumber.Icmp:
					this.IcmpTypeCodeList = MakeIcmpTypeCodeList(icmp4.pEntries);
					break;
				case IpProtocolNumber.IcmpV6:
					this.IcmpTypeCodeList = MakeIcmpTypeCodeList(icmp6.pEntries);
					break;
				default:
					break;
			}
		}

