	public record struct IcmpTypeCode(byte Type, ushort Code)
	{
		public override string ToString() =>
			((IcmpType)Type) switch
			{
				IcmpType.DestinationUnreachable => ((IcmpUnreachableCode)Code).ToString(),
				IcmpType.Redirect => $"Redirect:{((IcmpRedirectCode)Code).ToString()}",
				_ => $"{(IcmpType)Type}:{Code}"
			};
	}
	public sealed class IcmpTypeCodeList
	{
		public IcmpTypeCodeList(IcmpTypeCode[] typeCodes)
		{
			TypeCodes = typeCodes ?? [];
		}

		public IcmpTypeCode[] TypeCodes { get; }

		public sealed override string ToString() => string.Join(", ", TypeCodes.Select(r => r.ToString()));
	}

	public sealed class PortList
	{
		public PortList(FW_PORTS localPorts)
			: this((FW_PORT_KEYWORD)localPorts.wPortKeywords, localPorts.Ports)
		{
		}

		internal PortList(FW_PORT_KEYWORD keywords, FW_PORT_RANGE_LIST ranges)
		{
			Keywords = (FirewallPortKeywords)keywords;
			Ranges = ranges.pPorts?.value?.ConvertAll(r => new PortRange(r.wBegin, r.wEnd)) ?? [];
		}

		public FirewallPortKeywords Keywords { get; }
		public PortRange[] Ranges { get; }

		public sealed override string ToString() =>
			(Keywords != 0 && Ranges.Length > 0) ? $"{Keywords}, {string.Join(", ", Ranges.Select(r => r.ToString()))}"
			: (Keywords != 0) ? Keywords.ToString()
			: (Ranges != null) ? string.Join(", ", Ranges.Select(r => r.ToString()))
			: string.Empty;
	}
